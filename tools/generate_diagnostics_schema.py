#!/usr/bin/env python3
"""Generate consumers of the shared append-only diagnostic field registry."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate(schema):
 fields=schema['fields'];ids=[f['id'] for f in fields];paths=[f['path'] for f in fields]
 if len(set(ids))!=len(ids) or len(set(paths))!=len(paths) or any(not isinstance(i,int) or i<1 or i>65535 for i in ids):raise ValueError('Duplicate/invalid diagnostic ID or path')
 if any(any(not p.isidentifier() or p in ('__proto__','prototype','constructor') for p in path.split('.')) for path in paths):raise ValueError('Invalid diagnostic path')
 header='/* Generated by tools/generate_diagnostics_schema.py; do not edit. */\n#pragma once\n#define PH_DIAGNOSTICS_SCHEMA '+str(schema['schema'])+'\n'
 for f in fields:header+='#define PH_DIAG_'+f['path'].upper().replace('.','_')+' '+str(f['id'])+'u\n'
 js='// Generated from firmware common/diagnostics-schema.json; do not edit.\nconst diagnosticSchema='+str(schema['schema'])+';\nconst diagnosticFields='+json.dumps({f['id']:f['path'] for f in fields},separators=(',',':'))+';\n'
 return header,js
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--frontend-root',type=Path);p.add_argument('--hub-root',type=Path);a=p.parse_args()
 h,j=generate(json.loads((ROOT/'common/diagnostics-schema.json').read_text()))
 outputs={ROOT/'common/diagnostics_ids.h':h}
 if a.frontend_root:outputs[a.frontend_root/'common/web/diagnostics-schema.js']=j
 if a.hub_root:outputs[a.hub_root/'src/diagnostics_ids.h']=h
 for path,text in outputs.items():
  if a.check:
   if not path.exists() or path.read_text()!=text:raise SystemExit('Stale generated schema: '+str(path))
  else:path.write_text(text)
