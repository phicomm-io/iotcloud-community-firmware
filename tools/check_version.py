#!/usr/bin/env python3
"""Generate firmware version metadata from this project's Git repository."""
import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / 'common' / 'generated'
sys.path.insert(0, str(ROOT / 'tools/release'))
from release_version import TAG_PATTERN, parse_tag, parse_version


def git(root, *args):
    return subprocess.check_output(['git', '-C', str(root), *args],
                                   stderr=subprocess.DEVNULL, text=True).strip()


def resolve_version(root=ROOT, tag=None):
    root = Path(root).resolve()
    if tag and not TAG_PATTERN.fullmatch(tag):
        raise ValueError(f'Invalid release tag: {tag}; expected vMAJOR.MINOR.PATCH[-rc[.N]]')
    try:
        if Path(git(root, 'rev-parse', '--show-toplevel')).resolve() != root:
            raise ValueError('Source directory is not the Git repository root')
        commit = git(root, 'rev-parse', 'HEAD')
    except (OSError, subprocess.CalledProcessError, ValueError):
        if tag:
            raise ValueError('Release tag requires a project Git checkout')
        return {'version': '0.0.0-000000-dirty', 'base_version': '0.0.0',
                'git_commit': None, 'git_tag': None, 'dirty': True}

    explicit_tag = tag
    dirty = bool(git(root, 'status', '--porcelain', '--untracked-files=normal'))
    if tag:
        if git(root, 'rev-parse', f'refs/tags/{tag}^{{commit}}') != commit:
            raise ValueError(f'Release tag {tag} does not point to HEAD')
        if dirty:
            raise ValueError('Release tag build requires a clean source tree')
    else:
        tags = [t for t in git(root, 'tag', '--list', 'v*').splitlines()
                if TAG_PATTERN.fullmatch(t)]
        if tags:
            try:
                tag = git(root, 'describe', '--tags', '--abbrev=0',
                          *[arg for t in tags for arg in ('--match', t)], 'HEAD')
            except subprocess.CalledProcessError:
                tag = None
    base = tag[1:] if tag else '0.0.0'
    target_file = root / 'VERSION'
    if target_file.is_file():
        target = target_file.read_text().strip()
        if not TAG_PATTERN.fullmatch('v' + target) or parse_version(target).prerelease:
            raise ValueError('VERSION must contain MAJOR.MINOR.PATCH')
        if explicit_tag and parse_version(target).core != parse_tag(explicit_tag).core:
            raise ValueError('release tag differs from VERSION')
        if not explicit_tag and parse_version(target).core > parse_version(base).core:
            base, tag = target, None
    return {'version': f'{base}-{commit[:6]}' + ('-dirty' if dirty else ''),
            'base_version': base, 'git_commit': commit, 'git_tag': tag, 'dirty': dirty}


def ota_config(metadata=None):
    lines = ['/* Generated build-time OTA sources. */', '#pragma once']
    # Select a channel from release provenance at build time. Never let a
    # candidate accidentally query stable metadata, or fall back across lanes.
    candidate = bool(metadata and parse_version(metadata['base_version']).prerelease)
    channel = os.environ.get('PHICOMM_OTA_CHANNEL', '') or ('candidate' if candidate else 'stable')
    if channel not in ('candidate', 'stable'):
        raise ValueError('PHICOMM_OTA_CHANNEL must be candidate or stable')
    if candidate and channel != 'candidate':
        raise ValueError('Candidate firmware cannot use stable OTA metadata')
    lines.extend(['#ifndef PHICOMM_OTA_METADATA_PREFIX',
                  '#define PHICOMM_OTA_METADATA_PREFIX '+json.dumps('/ota/candidate' if channel == 'candidate' else '/ota/v1'),
                  '#endif'])
    for name in ('PHICOMM_OTA_CN_BASE_URL', 'PHICOMM_OTA_GLOBAL_BASE_URL', 'PHICOMM_OTA_GITHUB_BASE_URL'):
        value = os.environ.get(name, '').rstrip('/')
        if not value: continue
        pattern = r'https://[A-Za-z0-9.-]+(?::[0-9]+)?(?:/[A-Za-z0-9._-]+)*' if name.endswith('GITHUB_BASE_URL') else r'http://[A-Za-z0-9.-]+(?::[0-9]+)?'
        if not re.fullmatch(pattern, value) or len(value)>160:
            raise ValueError(name + ': expected a direct HTTP origin without path')
        lines.extend(['#ifndef '+name, '#define '+name+' '+json.dumps(value), '#endif'])
    return '\n'.join(lines)+'\n'


def generate(metadata):
    GENERATED.mkdir(parents=True, exist_ok=True)
    header = ('/* Generated by tools/check_version.py; do not edit. */\n'
              '#pragma once\n'
              f'#define FIRMWARE_VERSION "{metadata["version"]}"\n')
    for path, content in ((GENERATED / 'build_version.h', header),
                          (GENERATED / 'version.json', json.dumps(metadata, indent=2) + '\n'),
                          (GENERATED / 'build_ota.h', ota_config(metadata))):
        if not path.exists() or path.read_text() != content:
            path.write_text(content)


def build_metadata():
    """Read the build snapshot, without re-resolving Git during packaging."""
    return json.loads((GENERATED / 'version.json').read_text())


def project_version():
    return build_metadata()['version']


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--tag', help='Validate the exact CI release tag against HEAD')
    args = parser.parse_args()
    try:
        metadata = resolve_version(tag=args.tag)
        generate(metadata)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.error(str(error))
    print(f'Firmware version: {metadata["version"]}')
